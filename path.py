#!/usr/bin/env python3
"""The enemy formation's loop: one cycle's positions, FORM_TICKS of them.

The formation flies, at one constant speed, four straight legs, each the
diagonal of a box: northeast across a SQUARE x RISE box, east-southeast
across a RECT x RISE one, southwest across SQUARE x RISE, northwest across
SQUARE x RISE. A cycle takes CYCLE_SECS and leaves the formation RECT -
SQUARE px east of where it started, on the same lines. (The first spec's
boxes were 70x70, 120x70; cut to 58 tall to fit, then all halved, speed
too, the cycle's time kept. main.asm asserts that the formation, 44 px
tall, stays between the top status area and the front's sprite lines.)

Writes sjasmplus source to stdout:
  FORM_SQUARE, FORM_RECT, FORM_RISE  the boxes, in px
  FORM_ADVANCE    px east a cycle
  FORM_TICKS      path entries a cycle: TICK_RATE a second of CYCLE_SECS
  FORM_TICK_RATE  entries a second (main.asm steps them by Bresenham on
                  frames, so they need not divide the frame rate)
  FORM_PATH_DX_MAX  the largest dx in FORM_PATH
  FORM_PATH       FORM_TICKS x (dx, dy): the formation's offset from where
                  the cycle started, at tick i (dx 0.., dy signed; up is -)
  FREE_DIRS       a free enemy's directions (out of a broken pair): direction
                  d is d * 360 / FREE_DIRS degrees clockwise from east (y
                  grows down), so 1..FREE_DIRS/2-1 go down, the rest above
                  FREE_DIRS/2 up
  FREE_VEL_60, FREE_VEL_50  per direction, vx and vy (signed words) in
                  1/256 px a frame: the loop's speed (it's the same on every
                  leg, the square ones too), at that frame rate
"""
import math
import sys

SQUARE = 35         # px: the square boxes' width
RECT = 60           # px: the rectangle's width
RISE = 29           # px: every box's height
CYCLE_SECS = 1.8    # the only timing tunable

FREE_DIRS = 64      # a free enemy's directions

TICK_RATE = 300     # path entries a second: the table's resolution, at least
                    # one new place a frame at 60 Hz
TICKS = round(TICK_RATE * CYCLE_SECS)   # entries a cycle (the cycle is
                    # TICKS / TICK_RATE s: CYCLE_SECS to within 1/600 s)

LEGS = [(SQUARE, -RISE), (RECT, RISE), (-SQUARE, RISE), (-SQUARE, -RISE)]


def rnd(v):
    return math.floor(v + 0.5)


def main():
    rate = TICK_RATE
    assert rate >= 60 and TICKS > rate // 50, (rate, TICKS)
    assert sum(dy for _, dy in LEGS) == 0
    lengths = [math.hypot(dx, dy) for dx, dy in LEGS]
    total = sum(lengths)
    path = []
    for i in range(TICKS):
        s = i * total / TICKS
        x = y = 0.0
        for (dx, dy), l in zip(LEGS, lengths):
            if s <= l:
                x += dx * s / l
                y += dy * s / l
                break
            s -= l
            x += dx
            y += dy
        path.append((rnd(x), rnd(y)))
    dxs = [dx for dx, _ in path]
    assert min(dxs) >= 0 and max(dxs) < 256
    print('; Generated by path.py: do not edit')
    print(f'FORM_SQUARE     equ {SQUARE}')
    print(f'FORM_RECT       equ {RECT}')
    print(f'FORM_RISE       equ {RISE}')
    print(f'FORM_ADVANCE    equ {sum(dx for dx, _ in LEGS)}')
    print(f'FORM_TICKS      equ {TICKS}')
    print(f'FORM_TICK_RATE  equ {int(rate)}')
    print(f'FORM_PATH_DX_MAX equ {max(dxs)}')
    print(f'; {total:.1f} px a cycle of {TICKS / rate:.4f} s: {total * rate / TICKS:.1f} px/s')
    print('FORM_PATH:')
    for i in range(0, TICKS, 10):
        print('        db ' + ', '.join(f'{dx},{dy & 255:#04x}' for dx, dy in path[i:i + 10]))

    # A free enemy flies at the loop's speed, the square legs' as every leg's:
    # each leg's length over its time (its share of the cycle)
    sq = math.hypot(SQUARE, RISE)
    speed = sq / (TICKS / rate * sq / total)
    print(f'FREE_DIRS       equ {FREE_DIRS}')
    print(f'; free enemies: {speed:.2f} px/s')
    for fps in (60, 50):
        print(f'FREE_VEL_{fps}:')
        for d in range(FREE_DIRS):
            a = 2 * math.pi * d / FREE_DIRS
            vx = rnd(speed * math.cos(a) / fps * 256)
            vy = rnd(speed * math.sin(a) / fps * 256)
            assert (vy > 0) == (0 < d < FREE_DIRS // 2) and (vy < 0) == (d > FREE_DIRS // 2)
            print(f'        dw {vx}, {vy}')


if __name__ == '__main__':
    sys.exit(main())
