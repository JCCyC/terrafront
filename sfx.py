#!/usr/bin/env python3
"""Sound effects for the PSG, one table per frame rate (60 and 50 Hz).

SHOT_60, SHOT_50: the player's laser, a "cheeoom" SHOT_SECS long on one
channel. A burst of noise mixed with the tone for the first
SHOT_NOISE_SECS ("ch"), then the tone falls from SHOT_F0 to SHOT_F1 Hz.
The fall is exponential in time^SHOT_CURVE, so it lingers high ("ee")
and then drops fast ("oom"). The volume holds at SHOT_V0 and fades to
SHOT_V1 over the last part. Each frame plays the values at its middle.
Per frame: volume (1..15), tone period (2 bytes), mixer bits to switch on
(SHOT_NOISE_BIT for the noise, else 0); a 0 volume ends the table.
Also SHOT_NOISE (the noise period, R6).
Writes sjasmplus source to stdout.
"""
import sys

PSG_CLOCK = 1789773         # Hz: half the 3.579545 MHz master clock
SHOT_SECS = 0.25
SHOT_F0, SHOT_F1 = 2400.0, 160.0
SHOT_CURVE = 1.6
SHOT_NOISE_SECS = 0.035
SHOT_V0, SHOT_V1 = 15, 5
SHOT_FADE_FROM = 0.4        # fraction of the sound where the fade starts
SHOT_NOISE = 2              # noise period: a high hiss
SHOT_NOISE_BIT = 0x08       # mixer bit 3: channel A's noise (0 = on)


def shot(fps):
    n = int(SHOT_SECS * fps + 0.5)
    rows = []
    for i in range(n):
        t = (i + 0.5) / n
        f = SHOT_F0 * (SHOT_F1 / SHOT_F0) ** (t ** SHOT_CURVE)
        period = round(PSG_CLOCK / 16 / f)
        u = max(0.0, (t - SHOT_FADE_FROM) / (1 - SHOT_FADE_FROM))
        vol = round(SHOT_V0 + (SHOT_V1 - SHOT_V0) * u)
        noise = SHOT_NOISE_BIT if (i + 0.5) / fps < SHOT_NOISE_SECS else 0
        assert 1 <= vol <= 15 and 0 < period < 4096
        rows.append((vol, period, noise, f))
    return rows


def main():
    print('; Generated by sfx.py: do not edit')
    print(f'SHOT_NOISE      equ {SHOT_NOISE}')
    print(f'SHOT_NOISE_BIT  equ {SHOT_NOISE_BIT:#04x}')
    for fps in (60, 50):
        rows = shot(fps)
        print(f'SHOT_FRAMES_{fps}  equ {len(rows)}')
        print(f'SHOT_{fps}:')
        for vol, period, noise, f in rows:
            print(f'        db {vol},{period & 255},{period >> 8},{noise:#04x}   ; {f:4.0f} Hz')
        print('        db 0')


if __name__ == '__main__':
    sys.exit(main())
