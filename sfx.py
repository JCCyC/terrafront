#!/usr/bin/env python3
"""Sound effects for the PSG, one table per frame rate (60 and 50 Hz).

SHOT_60, SHOT_50: the player's laser, a "cheeoom" SHOT_SECS long on one
channel. A burst of noise mixed with the tone for the first
SHOT_NOISE_SECS ("ch"), then the tone falls from SHOT_F0 to SHOT_F1 Hz.
The fall is exponential in time^SHOT_CURVE, so it lingers high ("ee")
and then drops fast ("oom"). The volume holds at SHOT_V0 and fades to
SHOT_V1 over the last part. Each frame plays the values at its middle.
Per frame: volume (1..15), tone period (2 bytes), mixer bits to switch on
(SHOT_NOISE_BIT for the noise, else 0); a 0 volume ends the table.
Also SHOT_NOISE (the noise period, R6).

DEATH_60, DEATH_50: a player ship dying, Skyfighter's ship-blown-up sound
(its sfx.py's BOOM_SHIP, the same generator and values: U-boat Killer's
"water, loud" explosion), DEATH_SECS long on channel C. PSG noise gated
by a low tone on the same channel (the PSG ANDs tone and noise when both
are on), for a rumble. The top volume is held DEATH_HOLD s, then fades
linearly in PSG steps to 0 at the end; along the way the noise period
rises from its start value to its end value and the tone falls
exponentially (down to the PSG's lowest, 27.3 Hz, where it stays), so the
pitch drops. Per frame: volume (1..15), noise period, tone period (2
bytes); a 0 volume ends the table. Also DEATH_MIX: the mixer bits it
switches on (channel C's tone and noise), and DEATH_FRAMES_60/50.

BREAK_60, BREAK_50: an enemy pair breaking up, U-boat Killer's "miss"
(its BOOM_WATER, a depth charge exploding on the seabed with no sub
near; Skyfighter's BOOM_ROCK, the same tables): the death sound's
generator with a lower top volume, BREAK_SECS long, on channel B. The
same table layout; BREAK_MIX its mixer bits (channel B's tone and noise),
BREAK_FRAMES_60/50.
Writes sjasmplus source to stdout.
"""
import sys

PSG_CLOCK = 1789773         # Hz: half the 3.579545 MHz master clock
SHOT_SECS = 0.25
SHOT_F0, SHOT_F1 = 2400.0, 160.0
SHOT_CURVE = 1.6
SHOT_NOISE_SECS = 0.035
SHOT_V0, SHOT_V1 = 15, 5
SHOT_FADE_FROM = 0.4        # fraction of the sound where the fade starts
SHOT_NOISE = 2              # noise period: a high hiss
SHOT_NOISE_BIT = 0x08       # mixer bit 3: channel A's noise (0 = on)

DEATH_SECS = 1.4
DEATH_HOLD = 0.05           # s at the top volume
DEATH_TOP = 15
DEATH_N0, DEATH_N1 = 18, 31  # noise period, start and end
DEATH_F0, DEATH_F1 = 55.0, 22.5  # tone Hz, start and end
DEATH_MIX = 0x24            # mixer bits 2 and 5: channel C's tone and noise

BREAK_SECS = 0.8
BREAK_TOP = 13
BREAK_N0, BREAK_N1 = 20, 31
BREAK_F0, BREAK_F1 = 50.0, 25.0
BREAK_MIX = 0x12            # mixer bits 1 and 4: channel B's tone and noise


def shot(fps):
    n = int(SHOT_SECS * fps + 0.5)
    rows = []
    for i in range(n):
        t = (i + 0.5) / n
        f = SHOT_F0 * (SHOT_F1 / SHOT_F0) ** (t ** SHOT_CURVE)
        period = round(PSG_CLOCK / 16 / f)
        u = max(0.0, (t - SHOT_FADE_FROM) / (1 - SHOT_FADE_FROM))
        vol = round(SHOT_V0 + (SHOT_V1 - SHOT_V0) * u)
        noise = SHOT_NOISE_BIT if (i + 0.5) / fps < SHOT_NOISE_SECS else 0
        assert 1 <= vol <= 15 and 0 < period < 4096
        rows.append((vol, period, noise, f))
    return rows


def boom(fps, secs, top, n0, n1, f0, f1):
    n = round(secs * fps)
    hold = round(DEATH_HOLD * fps)
    rows = []
    for i in range(n):
        u = i / (n - 1)
        noise = round(n0 + (n1 - n0) * u)
        f = f0 * (f1 / f0) ** u
        period = min(4095, round(PSG_CLOCK / 16 / f))  # 27.3 Hz at the lowest
        vol = top if i < hold else round(top * (n - i) / (n - hold))
        vol = max(1, min(15, vol))
        assert 1 <= noise <= 31 and period < 4096
        rows.append((vol, noise, period, f))
    return rows


def main():
    print('; Generated by sfx.py: do not edit')
    print(f'SHOT_NOISE      equ {SHOT_NOISE}')
    print(f'SHOT_NOISE_BIT  equ {SHOT_NOISE_BIT:#04x}')
    for fps in (60, 50):
        rows = shot(fps)
        print(f'SHOT_FRAMES_{fps}  equ {len(rows)}')
        print(f'SHOT_{fps}:')
        for vol, period, noise, f in rows:
            print(f'        db {vol},{period & 255},{period >> 8},{noise:#04x}   ; {f:4.0f} Hz')
        print('        db 0')
    booms = [('DEATH', DEATH_MIX, (DEATH_SECS, DEATH_TOP, DEATH_N0, DEATH_N1, DEATH_F0, DEATH_F1)),
             ('BREAK', BREAK_MIX, (BREAK_SECS, BREAK_TOP, BREAK_N0, BREAK_N1, BREAK_F0, BREAK_F1))]
    for name, mix, args in booms:
        print(f'{name}_MIX       equ {mix:#04x}')
        for fps in (60, 50):
            rows = boom(fps, *args)
            print(f'{name}_FRAMES_{fps} equ {len(rows)}')
            print(f'{name}_{fps}:')
            for vol, noise, period, f in rows:
                print(f'        db {vol},{noise},{period & 255},{period >> 8}   ; {f:5.1f} Hz')
            print('        db 0')


if __name__ == '__main__':
    sys.exit(main())
